#!/usr/bin/env node
/**
 * Visual + axe pass over the AXIOM docs site on an ephemeral GCE spot VM —
 * never on the workstation (owner rule: browser tests run in the cloud).
 *
 *   node scripts/visual-cloud/run.mjs                              live site https://dragoscv.github.io/axiom/
 *   node scripts/visual-cloud/run.mjs --base <url>                 any deployed origin
 *   node scripts/visual-cloud/run.mjs --site-dist apps/site/dist   upload a local Astro build, serve it on the VM
 *
 * Options: --out <dir> (default <main clone>/.copilot-tmp/rc3/visual/<ts>),
 * --machine <type> (default e2-standard-4), --zone (default europe-central2-a),
 * --keep (do not delete the VM; debugging only), --vsix <file> (not supported, see README).
 *
 * Infra is brivio's (project brivio-488003): image family brivio-e2e-runner,
 * bucket brivio-e2e-runs-brivio-488003 under the prefix axiom/, service
 * account brivio-e2e-runner. Lifecycle: upload inputs → create spot VM with
 * vm-run.sh as startup script → tail the log from the bucket → download
 * results.tgz → ALWAYS delete the VM in `finally` and prove it with
 * `gcloud compute instances list --filter=name=<vm>`.
 *
 * Cost: e2-standard-4 spot ≈ 0.04 USD/h + 100 GB pd-balanced for ~15 min
 * ≈ 0.01–0.02 USD per run (list prices, europe-central2).
 *
 * Exit code = capture.mjs exit code on the VM (1 when a capture failed);
 * axe violations are reported in report.json, never fatal.
 */
import { execFileSync, spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, "../..");
const PROJECT = process.env.AXIOM_VISUAL_PROJECT ?? "brivio-488003";
const BUCKET = `brivio-e2e-runs-${PROJECT}`;
const SA = `brivio-e2e-runner@${PROJECT}.iam.gserviceaccount.com`;
const IMAGE_FAMILY = "brivio-e2e-runner";
// Pinned with `npm view <pkg> version` on 2026-10-19; installed ON THE VM only.
const PW_VERSION = "1.64.1";
const AXE_VERSION = "4.14.0";
const SERVE_VERSION = "14.2.6";
const SPOT_USD_PER_HOUR = { "e2-standard-4": 0.04, "e2-standard-8": 0.08, "n2d-standard-8": 0.09 };
const DEFAULT_BASE = "https://dragoscv.github.io/axiom/";

// ---------------------------------------------------------------- args --
const VALUED = new Set(["base", "site-dist", "out", "machine", "zone", "vsix"]);
const BOOL = new Set(["keep", "help"]);
const opt = new Map();
const argv = process.argv.slice(2);
for (let i = 0; i < argv.length; i++) {
  const m = /^--([a-z-]+)(?:=(.*))?$/.exec(argv[i]);
  if (m && VALUED.has(m[1])) opt.set(m[1], m[2] ?? argv[++i]);
  else if (m && BOOL.has(m[1])) opt.set(m[1], true);
  else {
    console.error(`visual-cloud: unknown argument ${argv[i]}`);
    process.exit(2);
  }
}
if (opt.get("help")) {
  console.log(readFileSync(fileURLToPath(import.meta.url), "utf8").split("*/")[0]);
  process.exit(0);
}
if (opt.has("vsix")) {
  console.error(
    "visual-cloud: --vsix is not supported: VS Code extension screenshots need a code-server image, and brivio-e2e-runner has none (see README).",
  );
  process.exit(2);
}
const siteDist = opt.has("site-dist") ? resolve(opt.get("site-dist")) : "";
if (siteDist && !existsSync(join(siteDist, "index.html"))) {
  console.error(
    `visual-cloud: --site-dist ${siteDist} has no index.html (run the Astro build first)`,
  );
  process.exit(2);
}
const base = siteDist
  ? "http://localhost:4321/axiom/"
  : (opt.get("base") ?? DEFAULT_BASE).replace(/\/?$/, "/");
if (!/^https?:\/\//.test(base)) {
  console.error(`visual-cloud: --base must be an http(s) URL (got ${base})`);
  process.exit(2);
}
const zone = opt.get("zone") ?? "europe-central2-a";
const machine = opt.get("machine") ?? "e2-standard-4";
const ts = new Date().toISOString().replace(/[-:]/g, "").replace("T", "-").slice(0, 15);
const runId = `${ts.toLowerCase()}-${Math.random().toString(36).slice(2, 6)}`;
const vm = `axiom-visual-${runId}`;
const RUN = `gs://${BUCKET}/axiom/runs/${runId}`;
const OUT = opt.get("out")
  ? resolve(opt.get("out"))
  : join(mainClone(), ".copilot-tmp", "rc3", "visual", ts);
const TMP = join(ROOT, ".copilot-tmp", "visual-cloud", runId);

// ---------------------------------------------------------------- helpers --
function sh(cmd, args, o = {}) {
  // gcloud is a .cmd on Windows, which spawn cannot start without a shell.
  // Every argument here is generated by this script (no user text with spaces/quotes).
  const r = spawnSync(cmd, args, {
    encoding: "utf8",
    shell: process.platform === "win32",
    maxBuffer: 1 << 26,
  });
  if (r.status !== 0 && !o.allowFail)
    throw new Error(`${cmd} ${args.join(" ")} → ${r.status}\n${(r.stderr ?? "").trim()}`);
  return { out: (r.stdout ?? "").trim(), err: (r.stderr ?? "").trim(), status: r.status };
}
const gcloud = (args, o) => sh("gcloud", [...args, `--project=${PROJECT}`], o);
const gsExists = (p) => gcloud(["storage", "ls", p], { allowFail: true }).status === 0;
const gsCat = (p) => gcloud(["storage", "cat", p], { allowFail: true }).out;
function mainClone() {
  try {
    const common = execFileSync(
      "git",
      ["rev-parse", "--path-format=absolute", "--git-common-dir"],
      { cwd: ROOT, encoding: "utf8" },
    ).trim();
    return dirname(common);
  } catch {
    return ROOT;
  }
}
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const t0 = Date.now();

// ---------------------------------------------------------------- run --
let exitCode = 1;
let created = false;
try {
  mkdirSync(TMP, { recursive: true });
  console.log(
    `▶ visual-cloud ${runId}  base=${base}${siteDist ? ` (local dist ${siteDist})` : ""}  vm=${vm} ${machine} spot ${zone}`,
  );
  writeFileSync(
    join(TMP, "config.env"),
    `BASE_URL=${base}\nPW_VERSION=${PW_VERSION}\nAXE_VERSION=${AXE_VERSION}\nSERVE_VERSION=${SERVE_VERSION}\n`,
  );
  gcloud(["storage", "cp", "-q", join(TMP, "config.env"), `${RUN}/config.env`]);
  gcloud(["storage", "cp", "-q", join(HERE, "capture.mjs"), `${RUN}/capture.mjs`]);
  if (siteDist) {
    const tgz = join(TMP, "site.tgz");
    execFileSync("tar", ["-czf", tgz, "-C", siteDist, "."]);
    console.log(`  site.tgz ${(readFileSync(tgz).length / 1048576).toFixed(1)} MB`);
    gcloud(["storage", "cp", "-q", tgz, `${RUN}/site.tgz`]);
  }
  const startup = join(TMP, "startup.sh");
  writeFileSync(startup, readFileSync(join(HERE, "vm-run.sh"), "utf8").replace(/\r\n/g, "\n"));

  gcloud([
    "compute",
    "instances",
    "create",
    vm,
    `--zone=${zone}`,
    `--machine-type=${machine}`,
    `--image-family=${IMAGE_FAMILY}`,
    `--image-project=${PROJECT}`,
    "--boot-disk-size=100GB",
    "--boot-disk-type=pd-balanced",
    "--provisioning-model=SPOT",
    "--instance-termination-action=DELETE",
    "--max-run-duration=1h",
    `--service-account=${SA}`,
    "--scopes=cloud-platform",
    "--labels=purpose=visual,owner=axiom",
    `--metadata=run-prefix=${RUN}`,
    `--metadata-from-file=startup-script=${startup}`,
  ]);
  created = true;
  console.log(`  VM created in ${((Date.now() - t0) / 1000).toFixed(0)} s`);

  let shown = 0;
  let lastAlive = Date.now();
  for (;;) {
    await sleep(10_000);
    const log = gsCat(`${RUN}/log`);
    if (log.length > shown) {
      process.stdout.write(log.slice(shown).replace(/^/gm, "  │ "));
      if (!log.endsWith("\n")) process.stdout.write("\n");
      shown = log.length;
    }
    if (gsExists(`${RUN}/exit-code`)) break;
    if (Date.now() - t0 > 25 * 60_000) throw new Error("no exit-code (done marker) after 25 min");
    if (Date.now() - lastAlive > 120_000) {
      lastAlive = Date.now();
      const alive = gcloud(
        ["compute", "instances", "describe", vm, `--zone=${zone}`, "--format=value(status)"],
        { allowFail: true },
      );
      if (alive.status !== 0) {
        await sleep(20_000);
        if (!gsExists(`${RUN}/exit-code`))
          throw new Error(`VM ${vm} is gone without an exit code (spot preemption?) - re-run`);
      }
    }
  }
  exitCode = Number(gsCat(`${RUN}/exit-code`) || 1);
  mkdirSync(OUT, { recursive: true });
  if (gsExists(`${RUN}/results.tgz`)) {
    const f = join(TMP, "results.tgz");
    gcloud(["storage", "cp", "-q", `${RUN}/results.tgz`, f]);
    execFileSync("tar", ["-xzf", f, "-C", OUT]);
  }
  const logText = gsCat(`${RUN}/log`);
  writeFileSync(join(OUT, "vm.log"), logText);
  let meta = {};
  try {
    meta = JSON.parse(gsCat(`${RUN}/meta.json`));
  } catch {
    /* VM died before writing it */
  }
  const usd = ((meta.seconds ?? 0) / 3600) * (SPOT_USD_PER_HOUR[machine] ?? 0.05);
  console.log(
    `${exitCode === 0 ? "✓" : "✗"} exit=${exitCode}  ${meta.seconds ?? "?"} s on ${machine}  ~$${usd.toFixed(3)} VM (+ disk, cents)`,
  );
  const reportFile = join(OUT, "report.json");
  if (existsSync(reportFile)) {
    const r = JSON.parse(readFileSync(reportFile, "utf8"));
    console.log(
      `  screenshots=${r.summary.screenshots}  capture errors=${r.summary.errors}  axe runs=${r.summary.axeRuns}`,
    );
    console.log(
      `  axe violations by impact (rule×page): ${JSON.stringify(r.summary.violationsByImpact)}`,
    );
    for (const rule of r.summary.topRules)
      console.log(
        `    ${rule.impact.padEnd(9)} ${rule.id.padEnd(28)} pages=${rule.pages} nodes=${rule.nodes}`,
      );
    for (const e of r.errors) console.log(`  ! ${e.where}: ${e.what}`);
  }
  console.log(`  results: ${OUT}`);
} catch (e) {
  console.error(`✗ visual-cloud: ${e?.message ?? e}`);
  exitCode = exitCode || 1;
} finally {
  if (created && !opt.get("keep")) {
    // The VM normally deletes itself; this covers a crash or interrupted follow.
    gcloud(
      ["compute", "instances", "delete", vm, `--zone=${zone}`, "--quiet", "--delete-disks=all"],
      { allowFail: true },
    );
  }
  if (created) {
    const list = gcloud(["compute", "instances", "list", `--filter=name=${vm}`, "--format=json"], {
      allowFail: true,
    });
    let n = -1;
    try {
      n = JSON.parse(list.out || "[]").length;
    } catch {
      /* unreadable */
    }
    console.log(
      `  VM deletion check: gcloud compute instances list --filter=name=${vm} → ${n} instance(s)${n === 0 ? " (deleted)" : opt.get("keep") ? " (--keep)" : " - STILL PRESENT, delete it by hand"}`,
    );
    if (n !== 0 && !opt.get("keep")) exitCode = exitCode || 1;
  }
  rmSync(TMP, { recursive: true, force: true });
}
process.exit(exitCode);
