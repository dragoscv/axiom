#!/usr/bin/env node
/**
 * Generate THIRD_PARTY_NOTICES.md for a package whose build bundles its dependencies.
 *
 *   node scripts/gen-third-party-notices.mjs --package packages/mcp [--out <file>]
 *
 * Walks the resolved runtime closure (`dependencies` + resolvable non-optional
 * `peerDependencies`) with Node's directory-walk resolution on real paths, so pnpm's
 * `.pnpm/<name>@<ver>/node_modules/<dep>` sibling layout resolves exactly as at runtime.
 * First-party `@codai/axiom-*` packages are traversed but not listed. For every third-party
 * package it records name, version, license, repository and the full text of every
 * LICENSE / LICENCE / COPYING / NOTICE file. Exits 1 when a dependency cannot be resolved
 * or declares no license. Output is deterministic (sorted, no timestamps).
 */
import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  realpathSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const args = process.argv.slice(2);
const argValue = (name) => {
  const i = args.indexOf(name);
  return i >= 0 ? args[i + 1] : undefined;
};
const pkgArg = argValue("--package");
if (!pkgArg) {
  console.error("usage: gen-third-party-notices.mjs --package <dir> [--out <file>]");
  process.exit(2);
}
const pkgDir = realpathSync(resolve(repoRoot, pkgArg));
const outFile = resolve(repoRoot, argValue("--out") ?? join(pkgDir, "THIRD_PARTY_NOTICES.md"));

const FIRST_PARTY = /^@codai\/axiom(-|$)/;
const NOTICE_FILE = /^(licen[cs]e|copying|notice)(\.|-|$)/i;

const readJson = (file) => JSON.parse(readFileSync(file, "utf8"));

/** Node-style resolution: <dir>/node_modules/<name>, then every parent directory. */
function resolveDep(fromDir, name) {
  let dir = fromDir;
  for (;;) {
    const candidate = join(dir, "node_modules", name, "package.json");
    if (existsSync(candidate)) return realpathSync(dirname(candidate));
    const parent = dirname(dir);
    if (parent === dir) return undefined;
    dir = parent;
  }
}

function licenseOf(pkg) {
  if (typeof pkg.license === "string") return pkg.license;
  if (pkg.license && typeof pkg.license.type === "string") return pkg.license.type;
  if (Array.isArray(pkg.licenses) && pkg.licenses.length > 0) {
    return pkg.licenses.map((l) => (typeof l === "string" ? l : l.type)).join(" OR ");
  }
  return undefined;
}

function repositoryOf(pkg) {
  const repo = typeof pkg.repository === "string" ? pkg.repository : pkg.repository?.url;
  return repo ? repo.replace(/^git\+/, "").replace(/\.git$/, "") : (pkg.homepage ?? "");
}

const seen = new Map(); // realpath → entry
const errors = [];

function visit(dir, viaName) {
  if (seen.has(dir)) return;
  const pkg = readJson(join(dir, "package.json"));
  const firstParty = dir === pkgDir || FIRST_PARTY.test(pkg.name ?? "");
  const entry = { dir, pkg, firstParty };
  seen.set(dir, entry);
  if (!firstParty) {
    entry.license = licenseOf(pkg);
    if (!entry.license) errors.push(`${pkg.name}@${pkg.version}: no license field`);
    entry.files = readdirSync(dir)
      .filter((f) => NOTICE_FILE.test(f))
      .sort()
      .map((f) => ({ name: f, text: readFileSync(join(dir, f), "utf8").replace(/\r\n/g, "\n") }));
  }
  const optionalPeers = pkg.peerDependenciesMeta ?? {};
  const deps = Object.keys(pkg.dependencies ?? {}).map((n) => [n, true]);
  for (const n of Object.keys(pkg.peerDependencies ?? {})) {
    if (!optionalPeers[n]?.optional) deps.push([n, false]);
  }
  for (const [name, required] of deps) {
    const target = resolveDep(dir, name);
    if (!target) {
      if (required) errors.push(`${pkg.name ?? viaName}: cannot resolve dependency ${name}`);
      continue;
    }
    visit(target, name);
  }
}

visit(pkgDir, "<root>");

if (errors.length > 0) {
  for (const e of errors) console.error(`gen-third-party-notices: ${e}`);
  process.exit(1);
}

const root = readJson(join(pkgDir, "package.json"));
const thirdParty = [...seen.values()]
  .filter((e) => !e.firstParty)
  .sort((a, b) =>
    `${a.pkg.name}@${a.pkg.version}`.localeCompare(`${b.pkg.name}@${b.pkg.version}`, "en"),
  );

const lines = [
  "# Third-party notices",
  "",
  `\`${root.name}\` bundles the following third-party packages into its distributed files.`,
  "Each is used under the license stated below; the full license and notice texts follow.",
  "This file is generated by `scripts/gen-third-party-notices.mjs` — do not edit by hand.",
  "",
  "| Package | Version | License | Repository |",
  "| --- | --- | --- | --- |",
  ...thirdParty.map(
    (e) => `| ${e.pkg.name} | ${e.pkg.version} | ${e.license} | ${repositoryOf(e.pkg) || "—"} |`,
  ),
  "",
];
for (const e of thirdParty) {
  lines.push("---", "", `## ${e.pkg.name}@${e.pkg.version}`, "", `License: ${e.license}`);
  const repo = repositoryOf(e.pkg);
  if (repo) lines.push(`Repository: ${repo}`);
  lines.push("");
  if (e.files.length === 0) {
    lines.push(
      `_No license file is shipped in the package; the declared license is ${e.license}._`,
      "",
    );
  }
  for (const f of e.files) {
    lines.push(`### ${f.name}`, "", "```text", f.text.trimEnd(), "```", "");
  }
}

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, `${lines.join("\n")}\n`);
console.error(
  `gen-third-party-notices: ${thirdParty.length} packages → ${relative(repoRoot, outFile)}`,
);
