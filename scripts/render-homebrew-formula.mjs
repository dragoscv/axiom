#!/usr/bin/env node
/**
 * Render the Homebrew formula for the standalone `axiom` binary (tap `dragoscv/homebrew-tap`).
 *
 *   node scripts/render-homebrew-formula.mjs <version> <path/to/SHA256SUMS> > Formula/axiom.rb
 *
 * The formula installs the Node SEA binaries attached to the GitHub release `v<version>` — the
 * same bytes `install.sh` downloads and the release's Sigstore attestation covers — so no Node
 * is needed. Every checksum comes from the release's own SHA256SUMS; a missing target fails
 * the render instead of emitting a formula that can never install.
 */
import { readFileSync } from "node:fs";

const [version, sumsPath] = process.argv.slice(2);
if (!version || !/^\d+\.\d+\.\d+$/.test(version) || !sumsPath) {
  console.error("usage: render-homebrew-formula.mjs <x.y.z> <SHA256SUMS>");
  process.exit(2);
}

const sums = new Map();
for (const line of readFileSync(sumsPath, "utf8").split(/\r?\n/)) {
  const m = /^([0-9a-f]{64})\s+\*?(\S+)$/.exec(line.trim());
  if (m) sums.set(m[2], m[1]);
}

const targets = ["darwin-arm64", "darwin-x64", "linux-arm64", "linux-x64"];
const sha = {};
for (const t of targets) {
  const v = sums.get(`axiom-${t}`);
  if (!v) {
    console.error(`render-homebrew-formula: axiom-${t} missing from ${sumsPath}`);
    process.exit(1);
  }
  sha[t] = v;
}

const base = `https://github.com/dragoscv/axiom/releases/download/v${version}`;
const block = (t) => `      url "${base}/axiom-${t}"
      sha256 "${sha[t]}"`;

process.stdout.write(`# typed: false
# frozen_string_literal: true

# Generated by dragoscv/axiom scripts/render-homebrew-formula.mjs — do not edit by hand.
class Axiom < Formula
  desc "Transactional write gate for coding agents (MCP server + CLI + hook)"
  homepage "https://dragoscv.github.io/axiom/"
  license "MIT"

  on_macos do
    on_arm do
${block("darwin-arm64")}
    end
    on_intel do
${block("darwin-x64")}
    end
  end

  on_linux do
    on_arm do
${block("linux-arm64")}
    end
    on_intel do
${block("linux-x64")}
    end
  end

  def install
    bin.install Dir["axiom-*"].first => "axiom"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/axiom --version")
  end
end
`);
